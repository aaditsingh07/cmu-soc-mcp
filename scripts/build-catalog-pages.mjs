// Regenerates src/catalog-pages.ts: which catalog department page(s) hold each
// two-digit course prefix. Run once per catalog year (`node scripts/build-catalog-pages.mjs`
// after `npm run build`). It reads the /coursedescriptions/ index and each department
// course page it links to, one at a time with a pause between requests. Only paths
// robots.txt allows are touched; nothing but the prefix map is kept.
import { writeFileSync } from "node:fs";
import { fetchText } from "../dist/http.js";
import { CATALOG_BASE, prefixesOnPage } from "../dist/catalog.js";

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const index = await fetchText(`${CATALOG_BASE}/coursedescriptions/`);
if (index.status !== 200) throw new Error(`index: HTTP ${index.status}`);
const paths = [
  ...new Set(
    [...index.body.matchAll(/href="(\/(?:schools-colleges|aboutcmu|intercollegeprograms)\/[^"#?]*courses\/)"/g)].map((m) => m[1])
  ),
].sort();

const map = {};
for (const path of paths) {
  await sleep(1000);
  const page = await fetchText(CATALOG_BASE + path);
  if (page.status !== 200) {
    console.error(`skip ${path}: HTTP ${page.status}`);
    continue;
  }
  const prefixes = prefixesOnPage(page.body);
  console.error(`${path}: ${prefixes.join(" ") || "(none)"}`);
  for (const p of prefixes) (map[p] ??= []).push(path);
}

const sorted = Object.fromEntries(Object.keys(map).sort().map((k) => [k, map[k]]));
writeFileSync(
  new URL("../src/catalog-pages.ts", import.meta.url),
  `// Generated by scripts/build-catalog-pages.mjs on ${new Date().toISOString().slice(0, 10)} from\n` +
    `// ${CATALOG_BASE}/coursedescriptions/ — regenerate once per catalog year.\n` +
    `// Course prefix -> catalog department page path(s) listing that prefix's courses.\n` +
    `export const CATALOG_PAGES: Record<string, string[]> = ${JSON.stringify(sorted, null, 2)};\n`
);
console.error(`wrote ${Object.keys(sorted).length} prefixes from ${paths.length} pages`);
